      AppLocale.uz => _uz,
      AppLocale.ru => _ru,
      AppLocale.en => _en,
    };
    return m[key] ?? _uz[key] ?? key;
  }

  /// `{{param}}` o‘rinlari bilan almashtiradi (RN `t(key, params)` ga yaqin).
  static String tParams(AppLocale locale, String key, Map<String, String> params) {
    String s = t(locale, key);
    for (final MapEntry<String, String> e in params.entries) {
      s = s.replaceAll('{{${e.key}}}', e.value);
    }
    return s;
